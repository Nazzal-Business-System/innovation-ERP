export async function seedNotifications(prisma: PrismaClient) {
  await prisma.notification.deleteMany({ where: { organizationId: ORG_ID } });

  for (const n of DEMO_NOTIFICATIONS) {
    await prisma.notification.create({
      data: {
        id: n.id,
        organizationId: ORG_ID,
        userId: n.userId ?? null,
        type: n.type,
        module: n.module,
        title: n.title,
        message: n.message,
        entityType: n.entityType ?? null,
        entityId: n.entityId ?? null,
        isRead: n.isRead,
        createdAt: n.createdAt,
      },
    });
  }

  return { notifications: DEMO_NOTIFICATIONS.length };
}
